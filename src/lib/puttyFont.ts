export const ROWS = 7;

export type Tone = 'on' | 'dim';

export interface Column {
  bits: boolean[];
  tone: Tone;
  /** Part of a colon, which can tick. */
  colon: boolean;
}

export const BLANK: Column = { bits: new Array(ROWS).fill(false), tone: 'on', colon: false };

/** A character the font has, or the nearest plain one, or a space. */
function plain(ch: string): string {
  if (FONT[ch]) return ch;
  if (ch === "'" || ch === '‘' || ch === '`') return '’';
  if (ch === '•' || ch === '∙') return '·';
  if (ch === '–' || ch === '—') return '-';
  const base = ch.normalize('NFD').replace(/[̀-ͯ]/g, '');
  if (FONT[base]) return base;
  if (ch === 'ß') return 'S';
  if (ch === 'Æ') return 'E';
  if (ch === 'Ø') return 'O';
  return ' ';
}

/** Upper-cased text as columns of dots, each glyph followed by a blank column. */
export function columns(text: string, toneAt?: (index: number) => Tone): Column[] {
  const cols: Column[] = [];
  [...text.toUpperCase()].forEach((raw, i) => {
    const ch = plain(raw);
    const glyph = FONT[ch];
    const tone = toneAt ? toneAt(i) : 'on';
    for (let c = 0; c < glyph[0].length; c++) {
      cols.push({ bits: glyph.map((row) => row[c] === '1'), tone, colon: ch === ':' });
    }
    cols.push(BLANK);
  });
  return cols;
}
